"""Test suite: easy + tricky questions, tool unit tests. Writes logs/example_runs.md.

Run:  python tests/run_tests.py
Tricky cases use MockLLM(flaky=True), which makes realistic first-attempt mistakes,
so you can see the verifier catch them and the agent retry.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agent import solve  # noqa: E402
from mock_llm import MockLLM  # noqa: E402
from tools import calc, fit_slots, fmt_duration, time_diff  # noqa: E402

SLOTS = "Free slots: 09:00\u201309:30, 09:45\u201310:30, 11:00\u201312:00."

# (name, question, expected_status, expected_answer_substring, expect_retry, flaky)
CASES = [
    ("easy-1 train", "If a train leaves at 14:30 and arrives at 18:05, how long is the journey?", "success", "3 hours 35 minutes", False, False),
    ("easy-2 apples", "Alice has 3 red apples and twice as many green apples as red. How many apples does she have in total?", "success", "9 apples", False, False),
    ("easy-3 slots", f"A meeting needs 60 minutes. {SLOTS} Which slots can fit the meeting?", "success", "11:00-12:00", False, False),
    ("easy-4 percent", "What is 15% of 240?", "success", "36", False, False),
    ("easy-5 distance", "A car travels at 60 km/h for 2.5 hours. How far does it travel?", "success", "150 km", False, False),
    ("easy-6 speed", "A car travels 150 km in 2.5 hours. What is its average speed?", "success", "60 km/h", False, False),
    ("easy-7 arithmetic", "What is 12 * 7 + 5?", "success", "89", False, False),
    ("easy-8 bus", "A bus leaves at 08:15 and arrives at 11:45. How long is the trip?", "success", "3 hours 30 minutes", False, False),
    ("tricky-1 midnight", "A train leaves at 23:30 and arrives at 02:15. How long is the journey?", "success", "2 hours 45 minutes", True, True),
    ("tricky-2 24h edge", "A train leaves at 12:00 and arrives at 12:00 the next day. How long is the journey?", "success", "24 hours", True, True),
    ("tricky-3 multi-step apples", "Alice has 3 red apples and twice as many green apples as red. She gives away 2 green apples. How many apples does she have now?", "success", "7 apples", True, True),
    ("tricky-4 slot boundary", f"A meeting needs 45 minutes. {SLOTS} Which slots can fit the meeting?", "success", "09:45-10:30, 11:00-12:00", True, True),
    ("tricky-5 box multi-step", "A shop has 3 boxes with 12 pens each. It sells 7 pens, then receives 2 more boxes of 12 pens. How many pens does it have now?", "success", "53 pens", False, True),
    ("tricky-6 discount then tax", "A jacket costs $80. It is discounted by 25%, then 10% tax is added. What is the final price?", "success", "$66.00", False, True),
    ("tricky-7 impossible count", "Bob has 5 red marbles and half as many blue marbles as red. How many marbles does he have in total?", "failed", None, True, True),
    ("tricky-8 missing data", "How old is the captain of the ship?", "failed", None, False, True),
]


def test_tools():
    assert time_diff("14:30", "18:05") == 215
    assert time_diff("23:30", "02:15", next_day=True) == 165
    assert time_diff("12:00", "12:00", next_day=True) == 1440
    try:
        time_diff("23:30", "02:15")
        raise AssertionError("expected ValueError")
    except ValueError:
        pass
    assert fit_slots(["09:00-09:30", "09:45-10:30", "11:00-12:00"], 45) == ["09:45-10:30", "11:00-12:00"]
    assert calc("3 + 3*2") == 9 and calc("5 + 5*0.5") == 7.5
    assert fmt_duration(215) == "3 hours 35 minutes" and fmt_duration(1440) == "24 hours" and fmt_duration(1) == "1 minute"
    try:
        calc("__import__('os')")
        raise AssertionError("expected ValueError")
    except ValueError:
        pass
    print("tool unit tests: ok")


def run():
    test_tools()
    lines = ["# Example run logs", "",
             "Generated by `python tests/run_tests.py` with the mock LLM. `Verifier passed` = status success; "
             "`Retried` = metadata.retries > 0.", ""]
    failures = 0
    print(f"{'case':30} {'status':8} {'verifier':9} {'retried':8} result")
    for name, q, want_status, want_ans, want_retry, flaky in CASES:
        out = solve(q, MockLLM(flaky=flaky), trace=False)
        retried = out["metadata"]["retries"] > 0
        ok = (out["status"] == want_status and (want_ans is None or want_ans in out["answer"])
              and (retried == want_retry))
        failures += not ok
        print(f"{name:30} {out['status']:8} {str(out['status'] == 'success'):9} {str(retried):8} {'PASS' if ok else 'FAIL'}")
        lines += [f"## {name} {'(PASS)' if ok else '(FAIL)'}", "", f"**Question:** {q}", "",
                  f"- Verifier passed: {out['status'] == 'success'}",
                  f"- Retried: {retried} (retries = {out['metadata']['retries']})", "",
                  "```json", json.dumps(out, indent=2, ensure_ascii=False), "```", ""]
    (ROOT / "logs").mkdir(exist_ok=True)
    (ROOT / "logs" / "example_runs.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{len(CASES) - failures}/{len(CASES)} passed. Log: logs/example_runs.md")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    run()
